-- Events: the host makes an actor come and go after this script has run, then calls verify.
local events = {}
entity.on_spawned(function(event) events[#events + 1] = {"spawned", event} end)
local leaving = entity.on_destroyed(function(event) events[#events + 1] = {"destroyed", event} end)
function verify()
    check(#replies == 2 and replies[1].dialog == question and replies[1].accepted == true)
    check(replies[2].dialog == note and replies[2].accepted == false, "dropped unshown")
    check(#events == 2 and events[1][1] == "spawned" and events[2][1] == "destroyed")
    local came, went = events[1][2], events[2][2]
    check(came.kind == "Sprout" and came.placement == 600 and came.team == 3 and came.location.x == 12)
    check(went.kind == "Sprout" and went.placement == 600 and went.actor == came.actor, "the same actor, by its handle")
    check(actor.alive(went.actor) == false)
    check(leaving:cancel() == true)
    check(#drops == 2 and drops[1].actor == bulborb and drops[1].attacker == captain and drops[1].previous == 40 and drops[1].life == 30)
    check(drops[2].life == 0 and #defeats == 1 and defeats[1].actor == bulborb and defeats[1].previous == 30)
    check(#deaths == 2 and deaths[1].pikmin == red and deaths[1].kind == "PikminRed" and deaths[1].attacker == bulborb and deaths[1].cause == "swallowed")
    check(deaths[2].cause == "#40" and deaths[2].attacker == nil, "a cause with no name is told as a string all the same: # and the game's number")
    check(#stage_changes == 1 and stage_changes[1].stage == "Story/DayEnd" and stage_changes[1].previous == "Story/StoryInGame")
    check(#steers == 1 and steers[1].player == 0 and steers[1].character == hound and steers[1].previous == player.captain(0))
    check(#changes == 1 and changes[1].actor == captain and changes[1].action == "Control/Whistle" and changes[1].previous == "Control/Walk")
end

