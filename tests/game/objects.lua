local idol_parts = component.list(idol)
check(#idol_parts == 4 and reflection.name(idol_parts[2]) == "Face" and reflection.name(idol_parts[3]) == "Nose")
local face, nose = component.find(idol, "face"), idol_parts[3]
check(face == idol_parts[2] and component.owner(nose) == idol)
none, why = component.find(idol, "Tail")
check(none == nil and why == "not_found")
